"""fit_data must fit with the propagation model the caller asked for.

The Marquardt-Levenberg routine (also the round-off stage of differential
evolution) rebuilt its p_dict from a fixed argument list that did not include
use_non_orthogonal or n_window, so every such fit silently used the orthogonal,
windowless model. On the Briscoe 2025 Regime I geometry that biased a T-only
fit by about 7 degC. These tests fit synthetic data generated by the requested
model and check both the recovered parameter and that the reported best fit is
that model's spectrum. Since #100 the non-orthogonal model is the default, so
a fit that names no model must use it, and the orthogonal (ES3) model must
still be used when asked for.
"""
import warnings

import numpy as np
import pytest

from elecsus.elecsus_methods import calculate, fit_data

# Briscoe et al. 2025, Regime I: oblique field, where the two propagation
# models differ by up to ~0.47 in transmission.
X = np.linspace(-6000, 8000, 300)
E_IN = np.array([0., 1., 0.])
E_IN_FIT = [0., [1., 0.]]
BASE = dict(Elem='Rb', Dline='D2', T=119.69, lcell=2e-3, Bfield=239.0,
            Btheta=np.deg2rad(80.), Bphi=0., GammaBuf=7.9, shift=0.)


def _spectrum(**extra):
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        [y] = calculate(X, E_IN, dict(BASE, **extra), outputs=['S0'])
    return np.real(y)


def _fit(y, start_T, algo='ML', **extra):
    p0 = dict(BASE, T=start_T, **extra)
    bounds = {'T': [start_T - 3., start_T + 3.]} if algo != 'ML' else None
    return fit_data([X, y], p0, {'T': True}, E_in=E_IN_FIT,
                    p_dict_bounds=bounds, data_type='S0', fit_algorithm=algo)


@pytest.mark.parametrize('extra', [
    dict(use_non_orthogonal=True),
    dict(use_non_orthogonal=True, n_window=1.51),
    dict(use_non_orthogonal=False),
], ids=['non-orthogonal', 'non-orthogonal+windows', 'orthogonal'])
def test_ml_fit_uses_the_requested_propagation_model(extra):
    y = _spectrum(**extra)
    best, rms, result = _fit(y, start_T=115.0, **extra)
    assert best['T'] == pytest.approx(BASE['T'], abs=0.05)
    assert rms < 1e-4
    expected = _spectrum(**dict(extra, T=best['T']))
    np.testing.assert_allclose(result.best_fit, expected, atol=1e-8)
    for key, value in extra.items():
        assert best[key] == value, f'{key} not reported back in best_params'


def test_a_fit_that_names_no_model_uses_the_non_orthogonal_one():
    """The default since #100: the data and the expected best fit are
    computed with the model named, the fit is given none."""
    y = _spectrum(use_non_orthogonal=True)
    best, rms, result = _fit(y, start_T=115.0)
    assert best['T'] == pytest.approx(BASE['T'], abs=0.05)
    assert rms < 1e-4
    expected = _spectrum(use_non_orthogonal=True, T=best['T'])
    np.testing.assert_allclose(result.best_fit, expected, atol=1e-8)


def test_models_differ_enough_for_the_test_to_mean_something():
    assert np.max(abs(_spectrum(use_non_orthogonal=True)
                      - _spectrum(use_non_orthogonal=False))) > 0.3


def test_differential_evolution_round_off_keeps_the_model(monkeypatch):
    """After DE, fit_data rebuilds the p_dict for the ML round-off from DE's
    best values, which hold only the model's own arguments. A real DE run takes
    ~15 s, so the DE stage is stubbed to return exactly that; the round-off is
    the real ML fit, and must still use the non-orthogonal model."""
    from elecsus.libs import MLFittingRoutine as ML
    real_ml_fit = ML.ML_fit

    def de_stub_then_real(data, E_in, p_dict, p_dict_bools, method='leastsq', **kw):
        if method == 'differential_evolution':
            return {k: v for k, v in p_dict.items()
                    if k not in ML.PROPAGATION_KEYS}, None
        return real_ml_fit(data, E_in, p_dict, p_dict_bools, method=method, **kw)

    monkeypatch.setattr(ML, 'ML_fit', de_stub_then_real)
    extra = dict(use_non_orthogonal=True)
    y = _spectrum(**extra)
    best, rms, result = _fit(y, start_T=118.0, algo='differential_evolution', **extra)
    assert best['T'] == pytest.approx(BASE['T'], abs=0.05)
    expected = _spectrum(**dict(extra, T=best['T']))
    np.testing.assert_allclose(result.best_fit, expected, atol=1e-8)
