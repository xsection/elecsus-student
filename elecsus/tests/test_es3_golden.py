"""
Golden-reference regression tests against genuine ElecSus v3.0.8.

The reference data (golden/es3_reference.npz) were generated by running the
final upstream durham-qlm/ElecSus commit (065fa28, v3.0.8) over a 20-case
parameter grid - see golden/generate_es3_reference.py for provenance and
regeneration instructions.

These tests give any user a quantitative statement of ES3/ES4 compatibility:

  * ES3 computed the mirror image (y -> -y) of its documented geometry: its B
    was effectively (sin t cos p, -sin t sin p, -cos t) for Btheta = t,
    Bphi = p (issue #56). ES4 computes the documented geometry, so v4 at
    Btheta = pi - t, Bphi = -p is the v3 calculation at (t, p). Every
    comparison below is made at that mirrored geometry.
  * There, S0, Ix, Iy are UNCHANGED between v3 and v4.
  * S1, S2 and S3 are the v3 values divided by S0 (fractional normalisation,
    a deliberate, documented v4 change). S3 has ES3's sign, Born & Wolf's:
    S3 > 0 when right-circular light dominates. (ES4 before #56 flipped it.)
  * Fractional Stokes comparisons are restricted to detuning points with
    S0 > 1e-2: at optically-thick line centres essentially no light is
    transmitted and S_i/S0 is a 0/0 ratio with no physical meaning.
  * ES3 truncated every transition frequency to whole MHz; ES4 keeps the
    exact value (issue #76), which moves S0 by up to ~3e-3 and S1-S3 by up
    to ~2e-2. These tests switch ES3's truncation back on
    (spectra._ES3_WHOLE_MHZ_LINES), so that they still pin everything else;
    test_line_frequencies.py bounds the difference the fix makes.
  * ES3 added 273.16, not 273.15, to the temperature in C for the Boltzmann
    populations (issue #61, E16.8); ES4 uses 273.15 for both, which moves the
    results by ~1e-8. These tests set spectra._KELVIN_BOLTZMANN back.
  * ES3 gave K41 4P1/2 the ground state's hyperfine constant (127.007 MHz for
    a measured 15.245 MHz; issue #84). These tests put it back, which only
    the K D1 case sees.
  * ES3 propagated with the orthogonal projection, which ES4 keeps as
    use_non_orthogonal=False. The default since #100 is the non-orthogonal
    solver, which differs in oblique fields (where ES3 was wrong by up to
    ~0.5 in S0), so every comparison here asks for ES3's method.
  * Oblique-field cases run through the v4 analytic Webber solver instead
    of the v3 SymPy solve, so they carry a looser (but still tight)
    tolerance; all other cases agree to ~1e-9.

Empirical worst-case deviations at time of writing: S0, Ix, Iy 2.3e-9
(non-oblique) and 7.6e-6 (oblique); fractional S1-S3 2.3e-8 and 8.3e-5.
"""
import os

import numpy as np
import pytest

from elecsus.elecsus_methods import calculate
from elecsus.libs import spectra
from elecsus.libs import AtomConstants as AC

GOLDEN = os.path.join(os.path.dirname(__file__), 'golden', 'es3_reference.npz')

_z = np.load(GOLDEN)
CASE_NAMES = [str(n) for n in _z['case_names']]

# opacity threshold below which fractional Stokes parameters are 0/0
S0_MASK = 1e-2


#: ES3's A(4P1/2) for K41, which is K41's ground-state constant (issue #84)
ES3_K41_D1_AP = 127.0069352


@pytest.fixture(autouse=True)
def es3_whole_mhz_lines(monkeypatch):
    """Reproduce ES3's whole-MHz line frequencies (issue #76), its K41
    P1/2 hyperfine constant (issue #84) and its 273.16 in the Boltzmann
    populations (issue #61)."""
    monkeypatch.setattr(spectra, '_ES3_WHOLE_MHZ_LINES', True)
    monkeypatch.setattr(spectra, '_KELVIN_BOLTZMANN', 273.16)
    monkeypatch.setattr(AC.K41_D1, 'Ap', ES3_K41_D1_AP)


def _load_case(name):
    X = _z[f'{name}__X']
    E_in = _z[f'{name}__E_in']
    p = eval(_z[f'{name}__p'].tobytes().decode())  # repr of a plain dict
    golden = {k: _z[f'{name}__{k}'].real for k in ['S0', 'S1', 'S2', 'S3', 'Ix', 'Iy']}
    return X, E_in, p, golden


def _es3_propagation(p):
    """p with ES3's (orthogonal) propagation, no longer the default (#100)."""
    return dict(p, use_non_orthogonal=False)


def _mirrored(p):
    """The v4 parameters that reproduce v3's calculation for p (issue #56)."""
    return _es3_propagation(dict(p, Btheta=np.pi - float(p.get('Btheta', 0.0)),
                                 Bphi=-float(p.get('Bphi', 0.0))))


def _is_oblique(p):
    """True when Btheta is neither Faraday (0, pi) nor Voigt (pi/2):
    those cases exercise the v4 analytic solver against v3's SymPy solve."""
    btheta = float(p.get('Btheta', 0.0))
    return min(abs(btheta % (np.pi / 2)), np.pi / 2 - abs(btheta % (np.pi / 2))) > 1e-9


@pytest.mark.parametrize('name', CASE_NAMES)
def test_s0_ix_iy_unchanged(name):
    X, E_in, p, g = _load_case(name)
    atol = 5e-5 if _is_oblique(p) else 1e-7
    res = calculate(X, E_in, _mirrored(p), outputs=['S0', 'Ix', 'Iy'])
    for key, arr in zip(['S0', 'Ix', 'Iy'], res):
        np.testing.assert_allclose(np.asarray(arr).squeeze().real, g[key],
                                   atol=atol, rtol=0,
                                   err_msg=f'{name}: {key} deviates from ES3 v3.0.8')


@pytest.mark.parametrize('name', CASE_NAMES)
def test_stokes_match_documented_transform(name):
    """v4 S1/S2/S3, at the mirrored geometry, must equal the v3 values under
    the documented transform: fractional normalisation."""
    X, E_in, p, g = _load_case(name)
    atol = 5e-4 if _is_oblique(p) else 1e-7
    m = g['S0'] > S0_MASK
    assert m.sum() > 50, f'{name}: mask leaves too few transmitting points'

    S1, S2, S3 = (np.asarray(a).squeeze().real
                  for a in calculate(X, E_in, _mirrored(p), outputs=['S1', 'S2', 'S3']))
    np.testing.assert_allclose(S1[m], g['S1'][m] / g['S0'][m], atol=atol, rtol=0,
                               err_msg=f'{name}: S1 != ES3 S1/S0')
    np.testing.assert_allclose(S2[m], g['S2'][m] / g['S0'][m], atol=atol, rtol=0,
                               err_msg=f'{name}: S2 != ES3 S2/S0')
    np.testing.assert_allclose(S3[m], g['S3'][m] / g['S0'][m], atol=atol, rtol=0,
                               err_msg=f'{name}: S3 != ES3 S3/S0')


def _linear_faraday(name):
    """Linearly polarised input with B along z (or B = 0): the mirror does not
    change S0 there, since reversing B only swaps the two circular modes."""
    X, E_in, p, g = _load_case(name)
    linear = abs(np.imag(np.conj(E_in[0]) * E_in[1])) < 1e-12 and abs(E_in[2]) < 1e-12
    return linear and abs(np.sin(float(p.get('Btheta', 0.0)))) < 1e-9


LINEAR_FARADAY = [name for name in CASE_NAMES if _linear_faraday(name)]


@pytest.mark.parametrize('name', LINEAR_FARADAY)
def test_linear_faraday_transmission_is_unchanged_at_the_same_geometry(name):
    """The common case, transmission of linear light in a longitudinal (or no)
    field, is still ES3's at the same Btheta. The mirror shows where a
    rotation's sense or an oblique field matters."""
    X, E_in, p, g = _load_case(name)
    S0, = calculate(X, E_in, _es3_propagation(p), outputs=['S0'])
    np.testing.assert_allclose(np.asarray(S0).squeeze().real, g['S0'], atol=1e-7, rtol=0)


def test_linear_faraday_cases_exist():
    assert len(LINEAR_FARADAY) >= 10
